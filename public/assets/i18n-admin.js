  function decorate(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script, style, textarea, [data-i18n]')) continue;
      const text = node.nodeValue.trim();
      const key = legacyByText.get(text);
      if (key && parent.childElementCount === 0) {
        parent.dataset.i18n = key;
        parent.textContent = window.AgentXI18n?.t?.(
          key,
          undefined,
          window.AgentXI18n?.getLocale?.() || document.documentElement.lang
        ) || text;
        continue;
      }
      if (parent.childElementCount > 0 || parent.dataset.i18nAdminPattern) continue;
      for (let index = 0; index < legacyPatterns.length; index += 1) {
        const match = text.match(legacyPatterns[index][0]);
        if (!match) continue;
        parent.dataset.i18nAdminPattern = String(index);
        parent.dataset.i18nAdminPatternValues = JSON.stringify(match.slice(1));
        applyPattern(parent);
        break;
      }
    }
  }

  function applyPattern(parent) {
    const index = Number.parseInt(parent.dataset.i18nAdminPattern || '', 10);
    const pattern = legacyPatterns[index];
    if (!pattern) return;
    let values = [];
    try { values = JSON.parse(parent.dataset.i18nAdminPatternValues || '[]'); } catch {}
    const locale = window.AgentXI18n?.getLocale?.() || document.documentElement.lang;
    parent.textContent = (locale === 'en-US' ? pattern[2] : pattern[1])(values);
  }

  function startLegacyDecorator() {
    if (!document.body) return;
    decorate(document.body);
    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        for (const node of mutation.addedNodes) {
          if (node.nodeType === Node.ELEMENT_NODE) decorate(node);
          if (node.nodeType === Node.TEXT_NODE && node.parentElement) decorate(node.parentElement);
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  if (document.body) startLegacyDecorator();
  else document.addEventListener('DOMContentLoaded', startLegacyDecorator, { once: true });
  window.addEventListener('localechange', () => {
    for (const node of document.querySelectorAll('[data-i18n-admin-pattern]')) applyPattern(node);
  });
